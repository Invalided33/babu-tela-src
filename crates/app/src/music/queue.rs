//! The shared queue of songs across everyone in a call: a list of items
//! and whose app is playing the current one (the "DJ"). The DJ is the
//! person who added the song and is still in the call; if they leave, the
//! next item's adder takes over.
//!
//! The state travels through the "controle" data channel of the voice
//! connections, in messages tagged `m-add`, `m-skip`, `m-pause`, `m-play`
//! and `m-state`. Nothing persists on the server: the queue dies with the
//! last person in the call.

use std::collections::VecDeque;
use std::sync::Arc;
use std::sync::atomic::{AtomicU64, Ordering};
use std::time::{Duration, Instant};

use serde::{Deserialize, Serialize};
use serde_json::{Value, json};

/// A song on the queue. The id is generated by whoever adds the song and
/// stays until the song is played or skipped. Services shared with yt-dlp
/// are the ones from [`Service`].
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct Item {
    pub id: String,
    pub url: String,
    pub title: String,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub uploader: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub duration: Option<u32>,
    pub service: String,
    /// Whose app is to play the song (the person who added it, by uid).
    pub by: i64,
    /// Display name of the person, so a late joiner can show it.
    pub by_name: String,
}

/// Whether the current song is playing or paused.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub enum State {
    #[default]
    Playing,
    Paused,
}

/// Public view of the queue: the first item (if any) is what the DJ is
/// playing; the rest are what comes next.
#[derive(Clone, Debug, Default)]
pub struct View {
    pub items: VecDeque<Item>,
    pub state: State,
    /// Seconds into the current song (how long it has been playing).
    pub elapsed: f32,
    /// Whose app is DJing right now: the first item's `by`, or `None` if
    /// nothing is playing. (The UI shows the dj's name from `by_name` on
    /// the first item instead.)
    #[allow(dead_code)]
    pub dj: Option<i64>,
}

/// The shared queue. All methods are safe to call from any thread.
pub struct Queue {
    inner: parking_lot_shim::Mutex<Inner>,
    /// Bumps every time the queue changes, so the UI can repaint without
    /// polling at full speed.
    generation: AtomicU64,
}

/// A tiny Mutex shim since the project avoids pulling in parking_lot: this
/// just re-exports `std::sync::Mutex` with the same `lock().unwrap()`
/// pattern (behind a module to make the pattern easy to replace later).
mod parking_lot_shim {
    pub use std::sync::Mutex;
}

struct Inner {
    items: VecDeque<Item>,
    state: State,
    /// When the current song started (or, after a pause, when it resumed).
    started_at: Option<Instant>,
    /// Seconds already played before the current `started_at`.
    offset: Duration,
    /// Who is in the call now, so a drop-off handovers the DJ to the next
    /// person with a song in the queue.
    members: Vec<i64>,
}

impl Default for Inner {
    fn default() -> Inner {
        Inner {
            items: VecDeque::new(),
            state: State::Playing,
            started_at: None,
            offset: Duration::ZERO,
            members: Vec::new(),
        }
    }
}

/// What the queue says to do next on this PC.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum DjAction {
    /// Nothing to do: not the DJ, or the queue is empty.
    Idle,
    /// Start playing this item.
    Play(Item),
    /// Pause the player.
    Pause,
    /// Stop the current playback (song finished or skipped).
    Stop,
}

impl Queue {
    pub fn new() -> Arc<Queue> {
        Arc::new(Queue {
            inner: parking_lot_shim::Mutex::new(Inner::default()),
            generation: AtomicU64::new(0),
        })
    }

    fn bump(&self) {
        self.generation.fetch_add(1, Ordering::Relaxed);
    }

    fn lock(&self) -> std::sync::MutexGuard<'_, Inner> {
        self.inner
            .lock()
            .unwrap_or_else(std::sync::PoisonError::into_inner)
    }

    pub fn view(&self) -> View {
        let g = self.lock();
        let elapsed = elapsed(&g);
        View {
            items: g.items.clone(),
            state: g.state,
            elapsed,
            dj: g.items.front().map(|it| it.by),
        }
    }

    /// The current song, if any (for the UI's "now playing").
    pub fn now_playing(&self) -> Option<Item> {
        self.lock().items.front().cloned()
    }

    /// What this PC's player should do: `me` is the local uid.
    pub fn action_for(&self, me: i64) -> DjAction {
        let g = self.lock();
        let Some(item) = g.items.front() else {
            return DjAction::Stop;
        };
        if item.by != me {
            return DjAction::Idle;
        }
        if g.state == State::Paused {
            return DjAction::Pause;
        }
        DjAction::Play(item.clone())
    }

    /// Sets who is in the call now, and promotes the next DJ when the
    /// current one is gone. Returns `true` when the head of the queue
    /// changed, so the orchestrator can start/stop playback.
    pub fn set_members(&self, members: &[i64]) -> bool {
        let mut g = self.lock();
        g.members = members.to_owned();
        let before = g.items.front().map(|it| it.id.clone());
        let members_now = g.members.clone();
        g.items.retain(|it| members_now.contains(&it.by));
        let after = g.items.front().map(|it| it.id.clone());
        if before != after {
            // The new head has not sent `m-start` yet: the elapsed clock
            // stays at 0 until its DJ actually begins playing.
            g.started_at = None;
            g.offset = Duration::ZERO;
            g.state = State::Playing;
        }
        drop(g);
        if before != after {
            self.bump();
            true
        } else {
            false
        }
    }

    /// Removes everything and reports it.
    pub fn clear(&self) {
        {
            let mut g = self.lock();
            g.items.clear();
            g.started_at = None;
            g.offset = Duration::ZERO;
            g.state = State::Playing;
        }
        self.bump();
    }

    /// Applies a message that came from someone over `controle`. Returns
    /// `true` when the state changed.
    pub fn apply(&self, msg: &Value) -> bool {
        match msg["t"].as_str() {
            Some("m-add") => {
                let Some(item) = parse_item(&msg["song"]) else {
                    return false;
                };
                self.add(item)
            }
            Some("m-skip") => {
                let Some(id) = msg["id"].as_str() else {
                    return false;
                };
                self.skip(id)
            }
            Some("m-pause") => self.set_paused(true),
            Some("m-play") => self.set_paused(false),
            Some("m-start") => {
                let Some(id) = msg["id"].as_str() else {
                    return false;
                };
                self.start_playing(id)
            }
            Some("m-state") => {
                let items = msg["queue"]
                    .as_array()
                    .map(|arr| arr.iter().filter_map(parse_item).collect::<VecDeque<_>>())
                    .unwrap_or_default();
                let state = if msg["paused"].as_bool() == Some(true) {
                    State::Paused
                } else {
                    State::Playing
                };
                let elapsed = msg["at"]
                    .as_f64()
                    .filter(|v| v.is_finite() && *v >= 0.0)
                    .map(Duration::from_secs_f64)
                    .unwrap_or_default();
                let changed = {
                    let mut g = self.lock();
                    if g.items.is_empty() {
                        g.items = items;
                        g.state = state;
                        g.offset = elapsed;
                        // Only roll the clock when the DJ had already
                        // begun playing: a snapshot of a song still being
                        // downloaded has `at == 0`, and the clock stays
                        // off until the DJ's `m-start` comes.
                        g.started_at = if state == State::Playing && elapsed > Duration::ZERO {
                            Some(Instant::now())
                        } else {
                            None
                        };
                        true
                    } else {
                        false
                    }
                };
                if changed {
                    self.bump();
                }
                changed
            }
            _ => false,
        }
    }

    /// Adds the item locally. Returns `true` if the queue changed. The
    /// clock stays off until the DJ sends `m-start`: the elapsed timer
    /// should not run while yt-dlp is still fetching.
    pub fn add(&self, item: Item) -> bool {
        let changed = {
            let mut g = self.lock();
            if g.items.iter().any(|i| i.id == item.id) {
                false
            } else {
                let was_empty = g.items.is_empty();
                g.items.push_back(item);
                if was_empty {
                    g.started_at = None;
                    g.offset = Duration::ZERO;
                    g.state = State::Playing;
                }
                true
            }
        };
        if changed {
            self.bump();
        }
        changed
    }

    /// Removes the item whose id matches (any position; usually the head).
    /// The next head gets a reset clock, off until its DJ sends `m-start`.
    pub fn skip(&self, id: &str) -> bool {
        let changed = {
            let mut g = self.lock();
            let before = g.items.front().map(|it| it.id.clone());
            if let Some(pos) = g.items.iter().position(|it| it.id == id) {
                g.items.remove(pos);
            }
            let after = g.items.front().map(|it| it.id.clone());
            if before != after {
                g.started_at = None;
                g.offset = Duration::ZERO;
                g.state = State::Playing;
                true
            } else {
                before != after || !g.items.is_empty() && g.items.len() + 1 != g.items.len()
            }
        };
        if changed {
            self.bump();
        }
        changed
    }

    /// Called when the DJ's player finishes the current song: drops its
    /// head.
    pub fn finished(&self, id: &str) -> bool {
        self.skip(id)
    }

    /// The DJ started playing the song whose id matches the head. Starts
    /// the elapsed clock from 0 for everyone, including the DJ (so the
    /// seconds the yt-dlp download took do not count).
    pub fn start_playing(&self, id: &str) -> bool {
        let changed = {
            let mut g = self.lock();
            match g.items.front() {
                Some(it) if it.id == id => {
                    g.started_at = Some(Instant::now());
                    g.offset = Duration::ZERO;
                    g.state = State::Playing;
                    true
                }
                _ => false,
            }
        };
        if changed {
            self.bump();
        }
        changed
    }

    pub fn set_paused(&self, paused: bool) -> bool {
        let changed = {
            let mut g = self.lock();
            match (g.state, paused) {
                (State::Playing, true) => {
                    if let Some(started) = g.started_at.take() {
                        g.offset = g.offset.saturating_add(started.elapsed());
                    }
                    g.state = State::Paused;
                    true
                }
                (State::Paused, false) => {
                    // Only roll the clock back on if it was already
                    // running when the pause came in (`offset > 0`).
                    // Otherwise the song had not started yet, and the
                    // DJ's `m-start` is what wakes the clock up.
                    if !g.offset.is_zero() {
                        g.started_at = Some(Instant::now());
                    }
                    g.state = State::Playing;
                    true
                }
                _ => false,
            }
        };
        if changed {
            self.bump();
        }
        changed
    }

    /// A snapshot of the whole queue, for `m-state` on a late joiner. The
    /// `elapsed` second count is included so the new copy sees the correct
    /// progress bar.
    pub fn snapshot_message(&self) -> Value {
        let g = self.lock();
        let elapsed = elapsed(&g);
        let items: Vec<Value> = g.items.iter().map(serialize_item).collect();
        json!({
            "t": "m-state",
            "queue": items,
            "paused": g.state == State::Paused,
            "at": elapsed,
        })
    }
}

/// Serialises an item to the shape `m-add` and `m-state` use.
fn serialize_item(item: &Item) -> Value {
    json!({
        "id": item.id,
        "url": item.url,
        "title": item.title,
        "uploader": item.uploader,
        "duration": item.duration,
        "service": item.service,
        "by": item.by,
        "byName": item.by_name,
    })
}

/// Reads an item from `m-add` / `m-state`'s shape.
fn parse_item(v: &Value) -> Option<Item> {
    Some(Item {
        id: v["id"].as_str()?.to_owned(),
        url: v["url"].as_str()?.to_owned(),
        title: v["title"].as_str().unwrap_or("desconhecido").to_owned(),
        uploader: v["uploader"].as_str().map(|s| s.to_owned()),
        duration: v["duration"].as_u64().map(|d| d as u32),
        service: v["service"].as_str().unwrap_or("").to_owned(),
        by: v["by"].as_i64()?,
        by_name: v["byName"].as_str().unwrap_or("").to_owned(),
    })
}

fn elapsed(g: &Inner) -> f32 {
    let mut total = g.offset;
    if let Some(started) = g.started_at {
        total = total.saturating_add(started.elapsed());
    }
    total.as_secs_f32()
}

/// Builds an `m-add` message.
pub fn add_message(item: &Item) -> Value {
    json!({ "t": "m-add", "song": serialize_item(item) })
}

/// Builds an `m-skip` message.
pub fn skip_message(id: &str) -> Value {
    json!({ "t": "m-skip", "id": id })
}

pub fn pause_message() -> Value {
    json!({ "t": "m-pause" })
}

pub fn play_message() -> Value {
    json!({ "t": "m-play" })
}

/// `m-start`: the DJ actually began playing `id`. The clock then starts.
pub fn start_message(id: &str) -> Value {
    json!({ "t": "m-start", "id": id })
}

/// Says `t` is one of this module's.
pub fn handles(t: &str) -> bool {
    matches!(
        t,
        "m-add" | "m-skip" | "m-pause" | "m-play" | "m-start" | "m-state"
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    fn item(id: &str, by: i64) -> Item {
        Item {
            id: id.to_owned(),
            url: format!("https://youtu.be/{id}"),
            title: format!("song {id}"),
            uploader: None,
            duration: Some(180),
            service: "YouTube".into(),
            by,
            by_name: "x".into(),
        }
    }

    #[test]
    fn add_puts_it_at_the_back_and_starts_the_clock() {
        let q = Queue::new();
        assert!(q.add(item("a", 1)));
        let v = q.view();
        assert_eq!(v.items.len(), 1);
        assert_eq!(v.dj, Some(1));
    }

    #[test]
    fn skip_moves_to_the_next_song() {
        let q = Queue::new();
        q.add(item("a", 1));
        q.add(item("b", 2));
        q.skip("a");
        let v = q.view();
        assert_eq!(v.items.front().unwrap().id, "b");
        assert_eq!(v.dj, Some(2));
    }

    #[test]
    fn pause_and_play_toggle_state() {
        let q = Queue::new();
        q.add(item("a", 1));
        q.set_paused(true);
        assert_eq!(q.view().state, State::Paused);
        q.set_paused(false);
        assert_eq!(q.view().state, State::Playing);
    }

    #[test]
    fn dropping_a_dj_hands_over() {
        let q = Queue::new();
        q.add(item("a", 1));
        q.add(item("b", 2));
        q.set_members(&[2]);
        let v = q.view();
        assert_eq!(v.dj, Some(2));
        assert_eq!(v.items.front().unwrap().id, "b");
    }

    #[test]
    fn action_for_the_dj_is_play() {
        let q = Queue::new();
        q.add(item("a", 7));
        match q.action_for(7) {
            DjAction::Play(it) => assert_eq!(it.id, "a"),
            x => panic!("{x:?}"),
        }
        assert_eq!(q.action_for(99), DjAction::Idle);
    }

    #[test]
    fn apply_adds_from_a_message() {
        let q = Queue::new();
        let msg = add_message(&item("x", 3));
        assert!(q.apply(&msg));
        assert_eq!(q.view().items.len(), 1);
    }

    #[test]
    fn adding_a_song_does_not_start_the_clock() {
        let q = Queue::new();
        q.add(item("a", 1));
        std::thread::sleep(std::time::Duration::from_millis(20));
        // The clock is still at 0 because the DJ has not sent `m-start`.
        assert!(q.view().elapsed < 0.01, "{}", q.view().elapsed);
    }

    #[test]
    fn start_playing_turns_the_clock_on() {
        let q = Queue::new();
        q.add(item("a", 1));
        assert!(q.start_playing("a"));
        std::thread::sleep(std::time::Duration::from_millis(20));
        assert!(q.view().elapsed > 0.01, "{}", q.view().elapsed);
    }

    #[test]
    fn start_playing_ignores_a_mismatched_id() {
        let q = Queue::new();
        q.add(item("a", 1));
        assert!(!q.start_playing("b"));
        assert!(q.view().elapsed < 0.01);
    }

    #[test]
    fn skipping_leaves_the_clock_off_for_the_next_song() {
        let q = Queue::new();
        q.add(item("a", 1));
        q.add(item("b", 2));
        q.start_playing("a");
        std::thread::sleep(std::time::Duration::from_millis(20));
        q.skip("a");
        // `b` is at the head but its DJ has not sent `m-start` yet.
        assert!(q.view().elapsed < 0.01, "{}", q.view().elapsed);
    }

    #[test]
    fn apply_starts_the_clock_from_m_start() {
        let q = Queue::new();
        q.add(item("x", 3));
        assert!(q.apply(&start_message("x")));
        std::thread::sleep(std::time::Duration::from_millis(20));
        assert!(q.view().elapsed > 0.01, "{}", q.view().elapsed);
    }

    #[test]
    fn apply_ignores_unknown_tags() {
        let q = Queue::new();
        assert!(!q.apply(&json!({ "t": "something" })));
    }

    #[test]
    fn snapshot_round_trips_through_apply() {
        let q = Queue::new();
        q.add(item("a", 1));
        q.add(item("b", 2));
        let snapshot = q.snapshot_message();

        let other = Queue::new();
        assert!(other.apply(&snapshot));
        assert_eq!(other.view().items.len(), 2);
    }

    #[test]
    fn an_apply_on_a_non_empty_queue_does_not_replay_state() {
        let q = Queue::new();
        q.add(item("a", 1));
        let other_snapshot = {
            let other = Queue::new();
            other.add(item("c", 3));
            other.snapshot_message()
        };
        // Already have songs: ignore the newcomer's state.
        assert!(!q.apply(&other_snapshot));
        assert_eq!(q.view().items.len(), 1);
    }
}
